import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import zlib from "node:zlib";

const canonicalDir = path.join(process.cwd(), "src", "data", "canonical");
const quranMetaPath = path.join(canonicalDir, "quran-meta.json");
const surahsDir = path.join(canonicalDir, "surahs");
const includeAllSurahs = process.argv.includes("--all");
const outPath = path.join(process.cwd(), "supabase", includeAllSurahs ? "seed-full.sql" : "seed.sql");

const rawMeta = fs.readFileSync(quranMetaPath, "utf8");
const quranMeta = JSON.parse(rawMeta);
const metaSha = crypto.createHash("sha256").update(rawMeta, "utf8").digest("hex");

const targetSurahIds = includeAllSurahs
  ? Array.from({ length: 114 }, (_, i) => i + 1)
  : [1, ...Array.from({ length: 37 }, (_, i) => 78 + i)];

const surahEntries = targetSurahIds.map((id) => {
  const filePath = path.join(surahsDir, `surah-${String(id).padStart(3, "0")}.json.gz`);
  return JSON.parse(zlib.gunzipSync(fs.readFileSync(filePath)).toString("utf8"));
});

const includedPagesSet = new Set();
for (const entry of surahEntries) {
  for (const v of entry.verses) {
    includedPagesSet.add(v.pageNumber);
  }
}
const includedPages = Array.from(includedPagesSet).sort((a, b) => a - b);

function sqlStr(val) {
  if (val === null || val === undefined) return "NULL";
  return `'${String(val).replace(/'/g, "''")}'`;
}

function chunkArray(arr, size) {
  const chunks = [];
  for (let i = 0; i < arr.length; i += size) {
    chunks.push(arr.slice(i, i + size));
  }
  return chunks;
}

const EDITION_ID_SUBQUERY = `(SELECT id FROM quran_editions WHERE slug = ${sqlStr(quranMeta.edition.slug)})`;

const lines = [
  `-- Generated by scripts/generate-supabase-seed.mjs from verified canonical per-Surah datasets (${includeAllSurahs ? "full 114-Surah" : "Al-Fatiha + Juz Amma SQL-Editor-friendly"} seed)`,
  `-- Surahs: ${surahEntries.length}, Pages: ${includedPages.length}, Meta SHA-256: ${metaSha}`,
  "",
  "BEGIN;",
  "",
  "INSERT INTO quran_editions (slug, name, script_type, total_pages, source_provider, source_version, license, checksum_sha256)",
  `VALUES (${sqlStr(quranMeta.edition.slug)}, ${sqlStr(quranMeta.edition.name)}, ${sqlStr(quranMeta.edition.scriptType)}, ${quranMeta.edition.totalPages}, 'Tanzil Project + Quran.com API v4', '1.1 / v4', 'CC BY 3.0 + Attribution', ${sqlStr(metaSha)})`,
  "ON CONFLICT (slug) DO UPDATE SET checksum_sha256 = EXCLUDED.checksum_sha256;",
  "",
  "INSERT INTO reciters (external_id, name, style, language_code, base_audio_url) VALUES",
  "  (7, 'Mishary Rashid al-Afasy', 'Murattal', 'ar', 'https://verses.quran.foundation/'),",
  "  (12, 'Mahmoud Khalil al-Husary', 'Muallim', 'ar', 'https://mirrors.quranicaudio.com/everyayah/Husary_Muallim_128kbps/')",
  "ON CONFLICT (external_id) DO NOTHING;",
  "",
];

// 1. Surahs
const surahValues = surahEntries.map(
  ({ surah }) =>
    `  (${surah.id}, ${sqlStr(surah.nameArabic)}, ${sqlStr(surah.nameSimple)}, ${sqlStr(surah.nameTurkish)}, ${sqlStr(surah.revelationPlace)}, ${surah.revelationOrder}, ${surah.versesCount}, ${surah.bismillahPre ? "TRUE" : "FALSE"})`
);
lines.push(
  "INSERT INTO surahs (id, name_arabic, name_simple, name_turkish, revelation_place, revelation_order, verses_count, bismillah_pre) VALUES",
  surahValues.join(",\n"),
  "ON CONFLICT (id) DO NOTHING;",
  ""
);

// 2. Mushaf Pages
const allVerses = [];
for (const entry of surahEntries) {
  for (const v of entry.verses) {
    allVerses.push(v);
  }
}

const pageValues = includedPages.map((p) => {
  const [juzNumber, hizbNumber] = quranMeta.pageJuzHizb[String(p)] ?? [1, 1];
  return `  (${EDITION_ID_SUBQUERY}, ${p}, ${juzNumber}, ${hizbNumber}, 15)`;
});
lines.push(
  "INSERT INTO mushaf_pages (edition_id, page_number, juz_number, hizb_number, lines_count) VALUES",
  pageValues.join(",\n"),
  "ON CONFLICT (edition_id, page_number) DO NOTHING;",
  ""
);

// 3. Ayahs (batched)
for (const chunk of chunkArray(allVerses, 100)) {
  const vals = chunk.map(
    (v) =>
      `  (${v.id}, ${v.surahId}, ${v.verseNumber}, ${sqlStr(v.verseKey)}, ${sqlStr(v.textUthmani)}, ${sqlStr(v.textImlaei)}, ${sqlStr(v.textUthmaniSha256)}, ${v.juzNumber}, ${v.hizbNumber}, ${v.rubElHizbNumber})`
  );
  lines.push(
    "INSERT INTO ayahs (id, surah_id, verse_number, verse_key, text_uthmani, text_imlaei, text_uthmani_sha256, juz_number, hizb_number, rub_el_hizb_number) VALUES",
    vals.join(",\n"),
    "ON CONFLICT (verse_key) DO NOTHING;",
    ""
  );
}

// 4. Page Ayah Mappings (batched)
for (const chunk of chunkArray(allVerses, 100)) {
  const vals = chunk.map((v) => {
    const wordLines = v.words.map((w) => w.lineNumber).filter((n) => Number.isFinite(n));
    const startLine = wordLines.length > 0 ? Math.min(...wordLines) : 1;
    const endLine = wordLines.length > 0 ? Math.max(...wordLines) : 1;
    return `  (${EDITION_ID_SUBQUERY}, ${v.pageNumber}, ${v.id}, ${startLine}, ${endLine})`;
  });
  lines.push(
    "INSERT INTO page_ayah_mappings (edition_id, page_number, ayah_id, start_line, end_line) VALUES",
    vals.join(",\n"),
    "ON CONFLICT (edition_id, page_number, ayah_id) DO NOTHING;",
    ""
  );
}

// 5. Verse Translations, Words & Morphology
const allTranslations = [];
const allWords = [];
const allMorphology = [];

for (const v of allVerses) {
  for (const tr of v.translations) {
    allTranslations.push({ ayahId: v.id, ...tr });
  }
  for (const w of v.words) {
    allWords.push({ ayahId: v.id, ...w });
    for (const seg of w.morphology.segments) {
      allMorphology.push({ wordId: w.id, ...seg });
    }
  }
}

for (const chunk of chunkArray(allTranslations, 150)) {
  const vals = chunk.map(
    (tr) =>
      `  (${tr.ayahId}, ${tr.resourceId}, ${sqlStr(tr.translatorName)}, ${sqlStr(tr.languageCode)}, ${sqlStr(tr.text)}, 'Quran.com API v4')`
  );
  lines.push(
    "INSERT INTO verse_translations (ayah_id, resource_id, translator_name, language_code, text, source_attribution) VALUES",
    vals.join(",\n"),
    "ON CONFLICT (ayah_id, resource_id) DO NOTHING;",
    ""
  );
}

for (const chunk of chunkArray(allWords, 150)) {
  const vals = chunk.map(
    (w) =>
      `  (${w.id}, ${w.ayahId}, ${w.position}, ${sqlStr(w.location)}, 'word', ${sqlStr(w.textUthmani)}, ${sqlStr(w.textImlaei)}, ${w.pageNumber}, ${w.lineNumber}, ${sqlStr(w.audioUrl)})`
  );
  lines.push(
    "INSERT INTO words (id, ayah_id, position, location, char_type, text_uthmani, text_imlaei, page_number, line_number, wbw_audio_path) VALUES",
    vals.join(",\n"),
    "ON CONFLICT (location) DO NOTHING;",
    ""
  );
}

for (const chunk of chunkArray(allWords, 150)) {
  const vals = chunk.map(
    (w) =>
      `  (${w.id}, 'tr', ${sqlStr(w.translationTr)}, ${sqlStr(w.transliteration)}, 'quran-com-v4-tr')`
  );
  lines.push(
    "INSERT INTO word_translations (word_id, language_code, translation_text, transliteration, source_id) VALUES",
    vals.join(",\n"),
    "ON CONFLICT (word_id, language_code, source_id) DO NOTHING;",
    ""
  );
}

for (const chunk of chunkArray(allMorphology, 200)) {
  const vals = chunk.map(
    (seg) =>
      `  (${seg.wordId}, ${seg.segmentIndex}, ${sqlStr(seg.segmentText)}, ${sqlStr(seg.partOfSpeech)}, ${sqlStr(seg.rootArabic)}, ${sqlStr(seg.lemmaArabic)}, ${sqlStr(JSON.stringify(seg.features))}::jsonb, 'quran-arabic-corpus-0.4')`
  );
  lines.push(
    "INSERT INTO word_morphology (word_id, segment_index, segment_text, part_of_speech, root_arabic, lemma_arabic, features_json, source_id) VALUES",
    vals.join(",\n"),
    "ON CONFLICT (word_id, segment_index, source_id) DO NOTHING;",
    ""
  );
}

lines.push(
  "SELECT setval(pg_get_serial_sequence('ayahs', 'id'), COALESCE((SELECT MAX(id) FROM ayahs), 1));",
  "",
  "COMMIT;"
);

fs.writeFileSync(outPath, lines.join("\n") + "\n", "utf8");
console.log(
  `Generated ${outPath}: ${surahEntries.length} surahs, ${includedPages.length} pages, ${allVerses.length} verses, ${allWords.length} words, ${allMorphology.length} morphology segments (${lines.length} lines).`
);

